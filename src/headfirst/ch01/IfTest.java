package headfirst.ch01;

// KELAS: IfTest
// Tujuan: Menunjukkan if sederhana
public class IfTest { // Mendefinisikan kelas IfTest
    public static void main(String[] args) { // Titik masuk program
        int x = 3; // Inisialisasi variabel x = 3
        if (x == 3) { // Jika x sama dengan 3
            System.out.println("x must be 3"); // Cetak pesan
        }
        System.out.println("This runs no matter what"); // Ini selalu dijalankan
    } // Akhir main
} // Akhir kelas
